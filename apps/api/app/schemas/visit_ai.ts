import Joi from 'joi';

export const summarizeSoapSchema = Joi.object({
  visitId: Joi.string().uuid().required(),
  rawNotes: Joi.string().min(1).required(),
  mood: Joi.string().optional().allow('', null),
  sessionId: Joi.string().optional().allow('', null),
  idempotencyKey: Joi.string().optional().allow('', null),
  vitalsList: Joi.array()
    .items(
      Joi.object({
        name: Joi.string().required(),
        value: Joi.alternatives().try(Joi.string(), Joi.number()).required(),
        unit: Joi.string().optional().allow('', null),
      })
    )
    .optional(),
  medicationsList: Joi.array()
    .items(
      Joi.object({
        name: Joi.string().required(),
        taken: Joi.boolean().required(),
        scheduledTime: Joi.string().optional().allow('', null),
      })
    )
    .optional(),
});

export const presignedAudioUploadSchema = Joi.object({
  mimeType: Joi.string()
    .valid(
      'audio/m4a',
      'audio/aac',
      'audio/mp4',
      'audio/wav',
      'audio/wave',
      'audio/x-wav',
      'audio/x-m4a',
      'audio/mpeg',
      'audio/mp3',
      'audio/webm',
      'audio/caf'
    )
    .default('audio/m4a')
    .required(),
  fileSize: Joi.number().integer().min(1).max(15 * 1024 * 1024).optional(),
});

export const evaluateVitalsSchema = Joi.object({
  vitalsList: Joi.array()
    .items(
      Joi.object({
        name: Joi.string().required(),
        value: Joi.alternatives().try(Joi.string(), Joi.number()).required(),
        unit: Joi.string().optional().allow('', null),
      })
    )
    .required(),
  rawNotes: Joi.string().optional().allow('', null),
});

/**
 * Strict schema for runtime validation of JSON generated by Gemini.
 * Enforces field presence, typed enums, and prevents malformed LLM responses.
 */
export const soapGeminiOutputSchema = Joi.object({
  subjective: Joi.string().required(),
  objective: Joi.string().required(),
  assessment: Joi.string().required(),
  plan: Joi.string().required(),
  overallStatus: Joi.string()
    .valid('Stable', 'Improved', 'Needs attention', 'Urgent')
    .required(),
  escalationLevel: Joi.string()
    .valid(
      'None',
      'Inform Field Manager (24 h)',
      'Care Manager review (same day)',
      'ERC now'
    )
    .default('None'),
  escalationReasons: Joi.array().items(Joi.string()).default([]),
  familyConnectSummary: Joi.string().allow('').default(''),
  followUpPrompts: Joi.array().items(Joi.string()).default([]),
}).unknown(true);

